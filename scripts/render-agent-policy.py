COMMON_AGENT_INSTRUCTIONS = (
    "Follow the caller's task brief, revision, evidence, and read/write scope. Do not broaden "
    "the task or delegate further. Return the requested result and identify unverified "
    "settings or limitations."
)


def role_definition(role):
    description, instructions, read_only = ROLE_DEFINITIONS[role]
    if read_only:
        instructions += " Do not modify files."
    return description, instructions + "\n\n" + COMMON_AGENT_INSTRUCTIONS, read_only


def codex_agent(role):
    description, instructions, read_only = role_definition(role)
    lines = [
        CODEX_AGENT_MARKER.rstrip("\n"),
        f'name = {json.dumps(role)}',
        f'description = {json.dumps(description)}',
    ]
    if read_only:
        lines.append('sandbox_mode = "read-only"')
    lines.extend(['developer_instructions = """', instructions, '"""', ''])
    return ROOT / f".codex/agents/{role}.toml", "\n".join(lines).encode()


def claude_agent(plugin, role, profile):
    description, instructions, _ = role_definition(role)
    frontmatter = ["---", f"name: {role}", f'description: "{description}"', f"model: {profile['model']}"]
    if profile["effort"] != "inherit":
        frontmatter.append(f"effort: {profile['effort']}")
    content = "\n".join(frontmatter + [
        "---",
        "",
        instructions,
        "",
    ])
    return ROOT / f"plugins/{plugin}/agents/{role}.md", content.encode()


def outputs():
    data = json.loads((SOURCE / "profiles.json").read_text())
    roles = data["roles"]
    for role in roles:
        yield codex_agent(role)
    table = "| 역할 | 모델 | 추론 | 기본 인원 |\n| --- | --- | --- | --- |\n"
    table += "".join(f"| `{name}` | `{p['model']}` | `{p['effort']}` | {p['count']} |\n"
                     for name, p in roles.items())
    header = ("<!-- Generated by scripts/render-agent-policy.py; edit shared/agent-policy. -->\n"
              f"# 모델 프로필 v{data['version']}\n\n확인 날짜: {data['verified_at']}. "
              "현재 native 도구 스키마와 사용자 지정을 우선한다.\n\n")
