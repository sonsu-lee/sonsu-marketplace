#!/usr/bin/env python3
"""Package shared policy references for standalone plugins; --check is read-only."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "shared/agent-policy"

CLAUDE_AGENT_DESCRIPTIONS = {
    "extraction": "Extracts requested facts and returns them in the requested structure.",
    "exploration": "Explores code and gathers evidence without broadening the assigned task.",
    "localized_implementation": "Implements a narrow, well-specified change and its focused verification.",
    "implementation": "Implements the assigned change and verifies its behavior.",
    "complex_design": "Analyzes a complex design boundary and returns evidence-backed options.",
    "general_review": "Independently reviews the complete assigned change with a fresh context.",
    "focused_review": "Reviews only the explicitly assigned scope with a fresh context.",
    "senior_review": "Provides an independent higher-capability review of the complete change.",
    "adjudication": "Checks reported findings against the evidence and contract.",
    "complex_adjudication": "Adjudicates findings involving complex state, permission, or compatibility boundaries.",
    "red_team": "Challenges the completed work against its fixed evidence and counterexamples.",
}


def claude_agent(plugin, role, profile):
    description = CLAUDE_AGENT_DESCRIPTIONS.get(
        role, f"Performs the assigned {role.replace('_', ' ')} work in an isolated context."
    )
    frontmatter = ["---", f"name: {role}", f'description: "{description}"', f"model: {profile['model']}"]
    if profile["effort"] != "inherit":
        frontmatter.append(f"effort: {profile['effort']}")
    content = "\n".join(frontmatter + [
        "---",
        "",
        "Follow the caller's delegation brief and its scope, evidence, and write boundaries. "
        "Do not broaden the task or delegate further unless explicitly asked. "
        "Return the requested result and identify any unverified settings or limitations.",
        "",
    ])
    return ROOT / f"plugins/{plugin}/agents/{role}.md", content.encode()


def outputs():
    data = json.loads((SOURCE / "profiles.json").read_text())
    roles = data["roles"]
    table = "| 역할 | 모델 | 추론 | 기본 인원 |\n| --- | --- | --- | --- |\n"
    table += "".join(f"| `{name}` | `{p['model']}` | `{p['effort']}` | {p['count']} |\n"
                     for name, p in roles.items())
    header = ("<!-- Generated by scripts/render-agent-policy.py; edit shared/agent-policy. -->\n"
              f"# 모델 프로필 v{data['version']}\n\n확인 날짜: {data['verified_at']}. "
              "현재 native 도구 스키마와 사용자 지정을 우선한다.\n\n")
    sources = "\n공식 근거: " + ", ".join(f"[출처 {i+1}]({url})" for i, url in enumerate(data["sources"])) + "\n"
    text = header + table + "\n" + (SOURCE / "prompt-deltas.md").read_text() + sources
    for plugin in ("engineering", "prompting"):
        yield ROOT / f"plugins/{plugin}/references/model-profiles.md", text.encode()
    yield ROOT / "plugins/engineering/references/model-profiles.json", (SOURCE / "profiles.json").read_bytes()
    claude = json.loads((SOURCE / "claude-profiles.json").read_text())
    claude_table = "| 역할 | 모델 | effort | 기본 인원 |\n| --- | --- | --- | --- |\n"
    claude_table += "".join(f"| `{name}` | `{p['model']}` | `{p['effort']}` | {p['count']} |\n"
                            for name, p in claude["roles"].items())
    claude_text = ("<!-- Generated by scripts/render-agent-policy.py; edit shared/agent-policy. -->\n"
                   f"# Claude Code 모델 프로필 v{claude['version']}\n\n"
                   f"확인 날짜: {claude['verified_at']}. 사용자 지정과 현재 native 도구 스키마가 우선한다.\n\n"
                   + claude_table + "\n" + (SOURCE / "claude-prompt-deltas.md").read_text()
                   + "\n공식 근거: " + ", ".join(f"[출처 {i+1}]({url})" for i, url in enumerate(claude["sources"])) + "\n")
    for plugin in ("engineering", "prompting"):
        yield ROOT / f"plugins/{plugin}/references/claude-model-profiles.md", claude_text.encode()
        for role, profile in claude["roles"].items():
            yield claude_agent(plugin, role, profile)
    yield ROOT / "plugins/engineering/references/claude-model-profiles.json", (SOURCE / "claude-profiles.json").read_bytes()
    authority = ("<!-- Generated by scripts/render-agent-policy.py; edit shared/agent-policy. -->\n" +
                 (SOURCE / "delivery-authority.md").read_text()).encode()
    for plugin in ("engineering", "workflow"):
        yield ROOT / f"plugins/{plugin}/references/delivery-authority.md", authority


def generated_agents():
    for plugin in ("engineering", "prompting"):
        yield from (ROOT / "plugins" / plugin / "agents").glob("*.md")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = dict(outputs())
    stale = []
    for path in sorted(set(generated_agents()) - set(rendered)):
        stale.append(str(path.relative_to(ROOT)))
        if not args.check:
            path.unlink()
    for path, data in rendered.items():
        if path.exists() and path.read_bytes() == data:
            continue
        stale.append(str(path.relative_to(ROOT)))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    for path in stale:
        print(("stale: " if args.check else "rendered: ") + path)
    return int(args.check and bool(stale))


if __name__ == "__main__":
    raise SystemExit(main())
