def generated_agents():
    for path in (ROOT / ".codex/agents").glob("*.toml"):
        if path.read_bytes().startswith(CODEX_AGENT_MARKER.encode()):
            yield path
    for plugin in ("engineering", "prompting"):
        yield from (ROOT / "plugins" / plugin / "agents").glob("*.md")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = dict(outputs())
    codex_agent_dir = ROOT / ".codex/agents"
    marker = CODEX_AGENT_MARKER.encode()
    conflicts = []
    for path, data in rendered.items():
        if path.parent != codex_agent_dir or not path.exists():
            continue
        existing = path.read_bytes()
        if existing != data and not existing.startswith(marker):
            conflicts.append(path)
    if conflicts:
        for path in conflicts:
            print("conflict: " + str(path.relative_to(ROOT)))
        return 1

    stale = []
    for path in sorted(set(generated_agents()) - set(rendered)):
        stale.append(str(path.relative_to(ROOT)))
        if not args.check:
            path.unlink()
    for path, data in rendered.items():
        if path.exists() and path.read_bytes() == data:
            continue
        stale.append(str(path.relative_to(ROOT)))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    for path in stale:
        print(("stale: " if args.check else "rendered: ") + path)
    return int(args.check and bool(stale))


if __name__ == "__main__":
    raise SystemExit(main())
