"""Exercise the writing projection CLI in a repository outside this checkout."""
import shutil
import re
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts/render-writing.py"
SOURCE = Path("plugins/writing/skills/writing")
TICKET = Path("plugins/workflow/skills/to-ticket")
PR = Path("plugins/workflow/skills/to-pr")
BANNER = "<!-- Generated by scripts/render-writing.py"


class ProjectionTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name) / "repo with spaces"
        self.root.mkdir()
        self.assertTrue(SCRIPT.is_file(), "writing projection capability is not implemented")
        self.sources = ["references/tickets.md", "references/pull-requests.md"] + [
            f"assets/templates/{name}.md" for name in
            ("default", "bug", "investigation", "pull-request")]
        for relative in self.sources:
            path = self.root / SOURCE / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(f"# {relative}\n\n한국어 日本語 English `Fixes #12`\n")
        (self.root / "plugins/writing/LICENSE").write_text("MIT License\n\nCopyright example\n")

    def run_cli(self, *args):
        return subprocess.run([sys.executable, str(SCRIPT), "--root", str(self.root), *args],
                              text=True, capture_output=True, timeout=15)

    def snapshot(self):
        return {str(p.relative_to(self.root)): p.read_bytes()
                for p in self.root.rglob("*") if p.is_file()}

    def test_builds_standalone_outputs_and_preserves_authored_bytes(self):
        result = self.run_cli()
        self.assertEqual(result.returncode, 0, result.stderr)
        pairs = [("references/tickets.md", TICKET / "references/ticket-writing.md"),
                 ("references/pull-requests.md", PR / "references/pr-writing.md")]
        pairs += [(f"assets/templates/{name}.md", TICKET / f"assets/templates/{name}.md")
                  for name in ("default", "bug", "investigation")]
        pairs.append(("assets/templates/pull-request.md", PR / "assets/templates/pull-request.md"))
        for source, target in pairs:
            data = (self.root / target).read_bytes()
            self.assertTrue(data.startswith(BANNER.encode()))
            self.assertEqual(data.split(b"\n\n", 1)[1], (self.root / SOURCE / source).read_bytes())
        self.assertEqual(self.run_cli("--check").returncode, 0)
        license_copy = self.root / "plugins/workflow/WRITING_LICENSE.md"
        self.assertEqual(license_copy.read_bytes().split(b"\n\n", 1)[1],
                         (self.root / "plugins/writing/LICENSE").read_bytes())
        shutil.rmtree(self.root / "plugins/writing")
        self.assertTrue((self.root / TICKET / "assets/templates/bug.md").is_file())
        self.assertTrue(license_copy.is_file())

    def test_check_reports_missing_and_changed_without_writing_then_build_repairs(self):
        before = self.snapshot()
        missing = self.run_cli("--check")
        self.assertNotEqual(missing.returncode, 0)
        self.assertIn("stale", missing.stderr)
        self.assertEqual(before, self.snapshot())
        self.assertEqual(self.run_cli().returncode, 0)
        target = self.root / TICKET / "references/ticket-writing.md"
        target.write_text("manual drift\n")
        before = self.snapshot()
        drift = self.run_cli("--check")
        self.assertNotEqual(drift.returncode, 0)
        self.assertIn("ticket-writing.md", drift.stderr)
        self.assertEqual(before, self.snapshot())
        self.assertEqual(self.run_cli().returncode, 0)
        self.assertEqual(self.run_cli("--check").returncode, 0)

    def test_obsolete_generated_file_is_removed_but_manual_file_survives(self):
        self.assertEqual(self.run_cli().returncode, 0)
        directory = self.root / TICKET / "references"
        old = directory / "old-writing.md"
        old.write_text(BANNER + " from removed-source; do not edit. -->\n\nold\n")
        manual = directory / "manual.md"
        manual.write_text("# Keep this hand-maintained rule\n")
        before = self.snapshot()
        result = self.run_cli("--check")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("obsolete", result.stderr)
        self.assertEqual(before, self.snapshot())
        self.assertEqual(self.run_cli().returncode, 0)
        self.assertFalse(old.exists())
        self.assertEqual(manual.read_text(), "# Keep this hand-maintained rule\n")

    def test_missing_source_fails_before_any_output_changes(self):
        self.assertEqual(self.run_cli().returncode, 0)
        (self.root / SOURCE / self.sources[0]).write_text("new source\n")
        (self.root / SOURCE / self.sources[-1]).unlink()
        before = self.snapshot()
        result = self.run_cli()
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("source", result.stderr)
        self.assertEqual(before, self.snapshot())

    def test_source_and_destination_symlinks_do_not_cross_package_boundary(self):
        outside = Path(self.tmp.name) / "outside"
        outside.mkdir()
        sentinel = outside / "sentinel.md"
        sentinel.write_text("do not touch\n")
        source = self.root / SOURCE / self.sources[0]
        source.unlink()
        source.symlink_to(sentinel)
        result = self.run_cli()
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("symlink", result.stderr)
        source.unlink()
        source.write_text("restored source\n")
        (self.root / TICKET).mkdir(parents=True)
        (self.root / TICKET / "references").symlink_to(outside, target_is_directory=True)
        result = self.run_cli()
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("symlink", result.stderr)
        self.assertEqual(list(outside.iterdir()), [sentinel])
        self.assertEqual(sentinel.read_text(), "do not touch\n")


class InstalledReferenceTests(unittest.TestCase):
    def test_skill_references_resolve_inside_each_standalone_package(self):
        for plugin in ("writing", "workflow"):
            package = (ROOT / "plugins" / plugin).resolve()
            for source in (package / "skills").rglob("*.md"):
                fence = None
                for line in source.read_text().splitlines():
                    stripped = line.lstrip()
                    if stripped.startswith(("```", "~~~")):
                        marker = stripped[:3]
                        fence = None if fence == marker else (marker if fence is None else fence)
                        continue
                    if fence:
                        continue
                    # Inline-code examples such as `[video](./clip.mp4)` are not
                    # package dependencies, just as fenced examples are not.
                    prose = re.sub(r"`+[^`]*`+", "", line)
                    for link in re.findall(r"\]\(([^)]+)\)", prose):
                        if "://" in link or link.startswith(("#", "mailto:")):
                            continue
                        destination = (source.parent / link.split("#", 1)[0]).resolve()
                        with self.subTest(plugin=plugin, source=source, link=link):
                            self.assertTrue(destination.exists(), "missing packaged reference")
                            self.assertIn(package, destination.parents,
                                          "skill reference requires an uninstalled package")


if __name__ == "__main__":
    unittest.main()
